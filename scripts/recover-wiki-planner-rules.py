"""Read selected IL as data; never load or execute the game's assemblies.

Requires the original catalog tool's client_metadata.py and its Python environment.
Example: python recover-wiki-planner-rules.py --metadata-tool /path/to/catalog-tool --assembly /path/to/Common.dll
"""
import argparse, hashlib, json, pathlib, re, sys

p=argparse.ArgumentParser();p.add_argument('--metadata-tool',required=True);p.add_argument('--assembly',required=True);a=p.parse_args()
sys.path.insert(0,a.metadata_tool)
from client_metadata import Metadata

expected='3fbe9d5a8199be8e95c449d4f4a981221c823cec70381c709d57c165888fca82'
assembly=pathlib.Path(a.assembly)
if hashlib.sha256(assembly.read_bytes()).hexdigest()!=expected:raise SystemExit('Assembly differs from the audited wiki snapshot; review the rules before extraction.')
m=Metadata(assembly);root=pathlib.Path(__file__).resolve().parents[1];out=root/'docs/wiki-evidence';out.mkdir(exist_ok=True)
extra={0x1b85,0x236e,0x2264,0x1bc5};methods=[];chests={}
for rid,row in enumerate(m.pe.net.mdtables.MethodDef.rows,1):
    owner=m.owners.get(id(row),'');name=str(row.Name)
    if rid not in extra and not ((owner in ('A.r','A.S') and name=='.cctor') or (owner=='Common.Game.Decorator' and ('Craft' in name or 'Workshop' in name))):continue
    il=m.evidence(rid);filename=f'{rid:08x}_{owner}_{name}.il.txt';(out/filename).write_text(il,encoding='utf-8')
    methods.append({'type':owner,'method':name,'token':f'0x{0x06000000+rid:08x}','file':filename,'sha256':hashlib.sha256(il.encode()).hexdigest()})
    if owner not in ('A.r','A.S'):continue
    chunks=re.split(r'\S+ ldc\.r4 ',il)[1:];groups=[]
    for index,chunk in enumerate(chunks):
        weight=float(chunk.split()[0]);labels=list(dict.fromkeys(re.findall(r'Common\.Local::(?:get_)?(\w+) token',chunk)))
        if weight<=0 or not labels:raise ValueError('Unrecognized reward initializer')
        groups.append({'id':index,'weight':weight,'labelKeys':labels})
    count=41 if owner=='A.r' else 5
    if len(groups)!=count:raise ValueError('Reward initializer count changed')
    chests['large' if owner=='A.r' else 'incan']={'groups':groups,'source':f'docs/wiki-evidence/{filename}','sourceSha256':hashlib.sha256(il.encode()).hexdigest(),'assemblySha256':expected,'kind':'entries' if owner=='A.r' else 'groups'}
(out/'manifest.json').write_text(json.dumps({'assemblySha256':expected,'methods':methods},indent=2),encoding='utf-8')
dest=root/'apps/api/src/wikiRecoveredChests.ts'
dest.write_text('// Generated by scripts/recover-wiki-planner-rules.py from hash-checked IL; not game execution.\nexport const recoveredChests = '+json.dumps(chests,indent=2)+';\n',encoding='utf-8')
print(json.dumps({k:{'entries':len(v['groups']),'weightTotal':sum(g['weight'] for g in v['groups'])} for k,v in chests.items()},indent=2))
